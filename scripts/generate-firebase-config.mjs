#!/usr/bin/env node
// Regenerates src/environments/firebase-config.generated.ts, run automatically before `build`
// and `start` (see package.json's `prebuild`/`prestart`) — same pattern as
// generate-build-info.mjs. Firebase App Hosting auto-populates FIREBASE_WEBAPP_CONFIG (a JSON
// string matching this exact shape) once a Firebase Web App is linked to the backend and the
// variable is declared in apphosting.yaml; outside that environment (local dev, a manually-run
// `ng build`) it falls back to the same values that used to be hardcoded directly into
// environment.ts/environment.development.ts.
//
// It also writes public/firebase-messaging-sw.js (gitignored, like favicon.svg): the Firebase Cloud
// Messaging worker needs the same config as literals, because a service worker cannot import the app.
import { realpathSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { messagingServiceWorker } from "./firebase-messaging-sw.mjs";

const FALLBACK = {
  apiKey: "AIzaSyC6Z81AaCJ-PLofq0N0Ize43oWMqKKW-zA",
  authDomain: "rosak-7223b.firebaseapp.com",
  projectId: "rosak-7223b",
  storageBucket: "rosak-7223b.appspot.com",
  messagingSenderId: "840290622352",
  appId: "1:840290622352:web:8ad6a7ca995f17042af115",
  measurementId: "G-QSNS80GX8D",
};

/**
 * The Firebase web config for an environment (`process.env` shape); pure apart from the warnings.
 * A field that is absent falls back silently (App Hosting omits what the linked Web App doesn't
 * have, e.g. measurementId without Analytics); one that is present but not a non-empty string
 * falls back with a warning, as does a value that isn't a JSON object.
 */
export function resolveFirebaseConfig(env) {
  const raw = env["FIREBASE_WEBAPP_CONFIG"];
  if (!raw) {
    return FALLBACK;
  }
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch {
    console.warn(
      "[generate-firebase-config] FIREBASE_WEBAPP_CONFIG is set but isn't valid JSON — using fallback.",
    );
    return FALLBACK;
  }
  if (parsed === null || typeof parsed !== "object" || Array.isArray(parsed)) {
    console.warn(
      "[generate-firebase-config] FIREBASE_WEBAPP_CONFIG isn't a JSON object — using fallback.",
    );
    return FALLBACK;
  }
  // Spread over FALLBACK rather than returning the parsed value as-is: Environment['firebase']
  // requires every field, so the ones App Hosting leaves out come from the fallback.
  const config = { ...FALLBACK, ...parsed };
  for (const key of Object.keys(FALLBACK)) {
    if (typeof config[key] !== "string" || config[key] === "") {
      if (key in parsed) {
        console.warn(
          `[generate-firebase-config] FIREBASE_WEBAPP_CONFIG.${key} isn't a non-empty string — using fallback.`,
        );
      }
      config[key] = FALLBACK[key];
    }
  }
  return config;
}

// Only write the files when run directly (`node scripts/generate-firebase-config.mjs`), not when
// a test imports resolveFirebaseConfig.
if (realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rootDir = join(dirname(fileURLToPath(import.meta.url)), "..");
  const outPath = join(rootDir, "src/environments/firebase-config.generated.ts");
  const config = resolveFirebaseConfig(process.env);

  writeFileSync(
    outPath,
    `// Generated by scripts/generate-firebase-config.mjs — do not edit by hand.\nexport const firebaseConfig = ${JSON.stringify(config, null, 4)};\n`,
  );

  // The installed SDK's version, so the worker's gstatic.com scripts match the page's firebase package.
  const sdkVersion = createRequire(import.meta.url)("firebase/package.json").version;
  writeFileSync(
    join(rootDir, "public/firebase-messaging-sw.js"),
    messagingServiceWorker(config, sdkVersion),
  );

  console.log(
    `[generate-firebase-config] using ${process.env["FIREBASE_WEBAPP_CONFIG"] ? "FIREBASE_WEBAPP_CONFIG" : "fallback"} values (project: ${config.projectId})`,
  );
}
