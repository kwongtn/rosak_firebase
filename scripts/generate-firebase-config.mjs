#!/usr/bin/env node
// Regenerates src/environments/firebase-config.generated.ts, run automatically before `build`
// and `start` (see package.json's `prebuild`/`prestart`) — same pattern as
// generate-build-info.mjs. Firebase App Hosting auto-populates FIREBASE_WEBAPP_CONFIG (a JSON
// string matching this exact shape) once a Firebase Web App is linked to the backend and the
// variable is declared in apphosting.yaml; outside that environment (local dev, a manually-run
// `ng build`) it falls back to the same values that used to be hardcoded directly into
// environment.ts/environment.development.ts.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const FALLBACK = {
  apiKey: "AIzaSyC6Z81AaCJ-PLofq0N0Ize43oWMqKKW-zA",
  authDomain: "rosak-7223b.firebaseapp.com",
  projectId: "rosak-7223b",
  storageBucket: "rosak-7223b.appspot.com",
  messagingSenderId: "840290622352",
  appId: "1:840290622352:web:8ad6a7ca995f17042af115",
  measurementId: "G-QSNS80GX8D",
};

function resolveConfig() {
  const raw = process.env["FIREBASE_WEBAPP_CONFIG"];
  if (!raw) {
    return FALLBACK;
  }
  try {
    // Spread over FALLBACK rather than returning the parsed value as-is: App Hosting's
    // auto-populated config omits fields the linked Web App doesn't have set (e.g.
    // measurementId when Analytics isn't enabled), but Environment['firebase'] requires them.
    return { ...FALLBACK, ...JSON.parse(raw) };
  } catch {
    console.warn(
      "[generate-firebase-config] FIREBASE_WEBAPP_CONFIG is set but isn't valid JSON — using fallback.",
    );
    return FALLBACK;
  }
}

const rootDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const outPath = join(rootDir, "src/environments/firebase-config.generated.ts");
const config = resolveConfig();

writeFileSync(
  outPath,
  `// Generated by scripts/generate-firebase-config.mjs — do not edit by hand.\nexport const firebaseConfig = ${JSON.stringify(config, null, 4)};\n`,
);

console.log(
  `[generate-firebase-config] using ${process.env["FIREBASE_WEBAPP_CONFIG"] ? "FIREBASE_WEBAPP_CONFIG" : "fallback"} values (project: ${config.projectId})`,
);
