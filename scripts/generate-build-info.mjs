#!/usr/bin/env node
// Regenerates src/build-info.ts from the current git state, run automatically before `build`
// and `start` (see package.json's `prebuild`/`prestart`). Ported from the intent of the old
// app's `angular-build-info` CLI step, without pulling in that package — this is the same idea
// (a tiny pre-build codegen step) in ~15 lines rather than a new dependency.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

function git(command, fallback) {
  try {
    return execSync(command, { encoding: "utf8" }).trim();
  } catch {
    return fallback;
  }
}

const hash = git("git rev-parse HEAD", "unknown");
const timestamp = new Date().toISOString();

const rootDir = join(dirname(fileURLToPath(import.meta.url)), "..");

const outPath = join(rootDir, "src/build-info.ts");
writeFileSync(
  outPath,
  `// Generated by scripts/generate-build-info.mjs — do not edit by hand.\nexport const buildInfo = {\n  hash: ${JSON.stringify(hash)},\n  timestamp: ${JSON.stringify(timestamp)},\n};\n`,
);

// Also written as a plain static asset (served as-is from `public/`, no build step of its own)
// so a running page can `fetch("/version.json")` to check what's *currently deployed* without
// re-downloading its own JS bundles — see NewVersionService, which polls this and compares
// `hash` against the one baked into the page's own already-loaded buildInfo above.
const versionJsonPath = join(rootDir, "public/version.json");
writeFileSync(versionJsonPath, `${JSON.stringify({ hash, timestamp })}\n`);

console.log(`[build-info] ${hash} @ ${timestamp}`);
