#!/usr/bin/env node
// Regenerates src/environments/runtime-config.generated.ts, run automatically before `build`
// and `start` (see package.json's `prebuild`/`prestart`) — same pattern as
// generate-firebase-config.mjs. Staging and production are the same Angular build
// (`environment.ts`, the CLI's default "production" configuration) deployed to two different
// App Hosting backends; the values that need to differ between them (backend URL, mapbox
// token, ...) come from apphosting.yaml's BUILD-time env vars instead of a second Angular
// fileReplacement, so each backend just needs its own apphosting.<environment-name>.yaml
// override (see apphosting.staging.yaml) rather than a source change per environment. Outside
// App Hosting (local dev, a manually-run `ng build`) this falls back to the production values.
import { realpathSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const FALLBACK = {
  backendUrl: "https://api-community.mlptf.org.my/",
  backendGraphqlUrl: "https://api-community.mlptf.org.my/graphql/",
  mapboxToken:
    "pk.eyJ1Ijoia3dvbmd0biIsImEiOiJjbHd3eGIxazEwd2tsMm5yM3NyYmt4b2s4In0.l1ThIQzGXxoPDY3VyMtC-Q",
  captchaSiteKey: "6Le4ekQhAAAAAKu_C7LTyylJfe8Q8Gv5fiNFx_kj",
  environmentName: "production",
  uploadConcurrency: 5,
  // The Web Push (VAPID) public key of the Firebase project, for the line alerts (core/push). Empty
  // until one is generated (see apphosting.yaml), and the alert bell then renders disabled.
  fcmVapidKey: "",
};

function resolveUploadConcurrency(raw) {
  if (!raw) {
    return FALLBACK.uploadConcurrency;
  }
  const value = Number(raw);
  if (Number.isInteger(value) && value > 0) {
    return value;
  }
  console.warn(
    `[generate-runtime-config] UPLOAD_CONCURRENCY=${JSON.stringify(raw)} isn't a positive integer — using ${FALLBACK.uploadConcurrency}.`,
  );
  return FALLBACK.uploadConcurrency;
}

/**
 * The runtime config for an environment (`process.env` shape); pure apart from the warning.
 * `||` rather than `??`: an empty env var must fall back too, or an empty BACKEND_URL would ship
 * as a base URL that makes every request relative to the site origin.
 */
export function resolveRuntimeConfig(env) {
  return {
    backendUrl: env["BACKEND_URL"] || FALLBACK.backendUrl,
    backendGraphqlUrl: env["BACKEND_GRAPHQL_URL"] || FALLBACK.backendGraphqlUrl,
    mapboxToken: env["MAPBOX_TOKEN"] || FALLBACK.mapboxToken,
    captchaSiteKey: env["CAPTCHA_SITE_KEY"] || FALLBACK.captchaSiteKey,
    environmentName: env["ENVIRONMENT_NAME"] || FALLBACK.environmentName,
    uploadConcurrency: resolveUploadConcurrency(env["UPLOAD_CONCURRENCY"]),
    fcmVapidKey: env["FCM_VAPID_KEY"] || FALLBACK.fcmVapidKey,
  };
}

// Only write the file when run directly (`node scripts/generate-runtime-config.mjs`), not when a
// test imports resolveRuntimeConfig.
if (realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const config = resolveRuntimeConfig(process.env);
  const rootDir = join(dirname(fileURLToPath(import.meta.url)), "..");
  const outPath = join(rootDir, "src/environments/runtime-config.generated.ts");

  writeFileSync(
    outPath,
    `// Generated by scripts/generate-runtime-config.mjs — do not edit by hand.\nexport const runtimeConfig = ${JSON.stringify(config, null, 4)};\n`,
  );

  console.log(
    `[generate-runtime-config] environment: ${config.environmentName}, backend: ${config.backendUrl}`,
  );
}
