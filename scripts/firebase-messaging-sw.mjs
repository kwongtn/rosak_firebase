// Pure builder for public/firebase-messaging-sw.js, the Firebase Cloud Messaging service worker that
// generate-firebase-config.mjs writes on every prestart/prebuild/pretest. Side-effect-free so the
// generated source can be unit-tested (src/app/firebase-messaging-sw.spec.ts), like favicon-select.mjs.
//
// The worker cannot import the app's bundle, so the Firebase config is inlined as literals and the
// compat SDK comes from gstatic.com through importScripts (the standard FCM pattern; the only
// external script the app loads this way). `sdkVersion` is the installed `firebase` package version,
// so the worker and the page run the same SDK release.
export function messagingServiceWorker(firebaseConfig, sdkVersion) {
  const sdk = `https://www.gstatic.com/firebasejs/${sdkVersion}`;
  return `// Generated by scripts/generate-firebase-config.mjs (scripts/firebase-messaging-sw.mjs). Do not edit.
// Firebase Cloud Messaging's own worker. The SDK registers it at its default scope,
// /firebase-cloud-messaging-push-scope, so it never controls a page and does not meet ngsw-worker.js at /.
importScripts("${sdk}/firebase-app-compat.js");
importScripts("${sdk}/firebase-messaging-compat.js");

// Added before firebase.messaging() adds the SDK's own click handler, so this one runs first and stops
// it: a tap on an alert focuses a tab already on its link, or opens the link. Same-origin links only.
self.addEventListener("notificationclick", (event) => {
  const message = event.notification.data && event.notification.data.FCM_MSG;
  // FCM may deliver webpush.fcm_options.link as notification.click_action; the SDK reads both too.
  const link =
    message &&
    ((message.fcmOptions && message.fcmOptions.link) ||
      (message.notification && message.notification.click_action));
  if (!link) {
    return;
  }
  event.stopImmediatePropagation();
  event.notification.close();
  const url = new URL(link, self.location.origin);
  if (url.origin !== self.location.origin) {
    return;
  }
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((clients) => {
      const open = clients.find((client) => client.url === url.href);
      return open ? open.focus() : self.clients.openWindow(url.href);
    }),
  );
});

firebase.initializeApp(${JSON.stringify(firebaseConfig)});
// Shows an alert that arrives while no tab of the app is visible; a visible tab gets it through
// onMessage instead (core/push/push.service.ts) and shows a toast.
firebase.messaging();
`;
}
